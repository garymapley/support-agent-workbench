def build_document(
    title: str,
    policy_type: str,
    version: str,
    active: bool,
    focus: str,
) -> str:
    active_text = "true" if active else "false"
    return f"""---
title: 演示商城{title}
policy_type: {policy_type}
version: "{version}"
effective_date: "2026-11-01"
is_active: {active_text}
---

# 演示商城{title}

> 说明：本文档完全是求职项目使用的虚构演示资料，不代表任何真实企业、品牌或平台的承诺。本文重点覆盖：{focus}。

## 适用范围与目标

本政策适用于演示商城自营订单的售后咨询、工单受理、人工复核和结果通知。客服或 Agent 必须先核验订单号、商品、购买渠道、履约状态与当前售后状态，再使用本文作出流程建议。第三方商家、线下交易、无法核验的订单以及涉及司法争议的事项不直接适用，应转交人工专员确认。政策的目标是让客户获得一致、可解释、可追踪的处理结果，同时避免在证据不足时承诺退款、换货、赔偿或免费维修。

## 受理条件

围绕“{focus}”的申请必须由订单本人或经授权的联系人提出。受理人员应记录问题发生时间、商品现状、客户期望、已尝试步骤以及是否存在重复工单。订单处于取消中、退款中、拒付调查中或已有人工审批时，不得重复创建相同动作。信息缺失时可以创建待补充工单，但不得把待核实事项描述为已经确认的责任结论。涉及退款的处理，无论模型给出何种建议，都必须遵守系统中的人工审批状态。

## 必要材料与证据

标准材料包括订单号、商品或包裹照片、问题描述、发生时间和可联系信息。功能异常应优先收集连续视频、指示灯状态、报错内容和基础排查结果；物流异常应记录运单号、轨迹截图、外包装六面照片、面单与称重信息；金额争议应保留支付明细、优惠分摊和退款计算过程。证据只用于当前售后事项，客服不得要求客户提交与问题无关的身份证件、银行卡密码、短信验证码或账户口令。

## 标准处理流程

第一步是查询订单和已有工单，确认没有重复处理。第二步是检索当前生效政策，并在回复中记录政策来源和版本。第三步根据证据完成低风险排查；无法确定时创建人工接管工单。第四步给出建议动作及风险等级。第五步在需要退款、赔付或其他资金动作时创建审批并暂停自动流程。第六步由有权限的审核人作出通过或拒绝决定。第七步通知客户结果和下一步，但审批通过只代表允许进入执行环节，不等于资金已经到账。

## 时效与升级规则

普通咨询应在工单创建后一个工作日内首次响应；需要承运商、仓库或检测中心配合时，应向客户说明正在调查以及下一次更新时间，不得虚构确定完成时间。连续四十八小时没有外部进展的工单应升级复核。客户重复联系、材料相互矛盾、同一设备多次申请、金额达到五百元、订单已有退款记录或系统检测到异常行为时，必须提升风险等级并转人工处理。

## 审批与权限边界

Agent 可以查询、分类、检索政策、创建工单和生成处理建议，但不能自行完成退款、转账、赔偿、账户封禁或责任认定。人工审核必须记录审批号、关联对话 thread_id、审核人、决定、备注和时间。审核人不得审批自己伪造或无法追溯的申请。拒绝时应说明缺失条件或证据，不得只返回模糊结论。审批通过后，执行系统仍需校验订单状态，避免重复退款或对已经关闭的订单再次操作。

## 客户沟通规范

回复应使用清晰、克制和可验证的语言，区分“已受理”“等待材料”“等待审批”“审批通过待执行”和“已执行”五种状态。不得把预计时间表述为保证时间，不得引用已失效政策，不得隐藏可能由客户承担的运费、检测费或价差。引用本政策时应同时标注 source 与 version。客户情绪激动时仍应先复述事实和当前状态，再提供明确的下一步，而不是与客户争辩。

## 例外与人工接管

下列情况直接转人工：订单信息无法匹配；客户提供的证据疑似被编辑；商品涉及人身安全、隐私泄露或批量质量问题；同一账户短期内出现大量高金额申请；政策之间存在冲突；系统工具调用失败；客户要求超出政策授权。人工可以根据完整证据作出例外决定，但必须留下原因，不能通过口头指令绕过审批记录。例外决定只适用于对应订单，不自动形成新的通用政策。

## 审计、隐私与数据保留

系统应保留工具调用、命中的政策版本、工单状态变化和人工审批轨迹，以便复盘与评测。日志不得写入完整 API Key、密码、验证码和不必要的个人敏感信息。用于演示的客户姓名、订单与金额均为虚构数据。政策更新后应重新导入向量库，并通过 is_active 字段过滤旧版本；历史工单仍需保存当时引用的 source 和 version，以便解释当时为何作出对应建议。

## 示例判断

当客户的问题符合“{focus}”且订单、材料和时间条件完整时，Agent 可以创建工单并说明后续步骤；如果建议动作包含退款，系统必须自动生成待审批记录并暂停主对话。审核人通过后，Agent 应说明“审批已通过，等待执行或后续系统处理”，而不能说“退款已经到账”。如果审核人拒绝，Agent 应引用审核备注并告知可以补充哪些材料。若本文 is_active 为 false，检索层必须排除本文，不得用它回答当前客户。
"""


def main() -> None:
    knowledge_dir = Path("knowledge")
    knowledge_dir.mkdir(parents=True, exist_ok=True)
    for filename, title, policy_type, version, active, focus in POLICIES:
        document = build_document(title, policy_type, version, active, focus)
        (knowledge_dir / filename).write_text(document, encoding="utf-8")
    print(f"已生成 {len(POLICIES)} 篇演示政策文档。")


if __name__ == "__main__":
    main()
